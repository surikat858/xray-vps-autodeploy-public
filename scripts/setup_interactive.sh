#!/usr/bin/env bash
# Interactive configuration wizard for a FRESH Ubuntu 24.04 VPS only.
# Launch from the checked-out repository as root. No secrets are printed.
set -Eeuo pipefail
umask 077

die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }
[[ $(id -u) -eq 0 ]] || die 'Запустите через sudo или от root.'
[[ -t 0 && -t 1 ]] || die 'Требуется интерактивный терминал (TTY).'
[[ $(. /etc/os-release; printf '%s:%s' "$ID" "$VERSION_ID") == ubuntu:24.04 ]] || die 'Требуется Ubuntu 24.04.'
[[ $(uname -m) == x86_64 ]] || die 'Требуется x86_64.'
[[ ! -e /etc/x-ui/x-ui.db && ! -e /usr/local/x-ui/x-ui ]] || die 'Обнаружена существующая 3X-UI; установка поверх неё запрещена.'
[[ ! -f /var/run/reboot-required ]] || die 'ОС требует перезагрузку. Перезагрузите VPS и повторите установку.'
BASE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
[[ -f "$BASE/install.sh" && -f "$BASE/config.example.env" ]] || die 'Неполный репозиторий.'
CFG="$BASE/config.env"
[[ ! -e "$CFG" ]] || die "Файл $CFG уже есть. Для защиты настроек мастер не перезаписывает его; продолжите вручную."

prompt() {
    local label=$1 default=$2 answer
    read -r -p "$label [$default]: " answer
    REPLY_VALUE="${answer:-$default}"
}
valid_port() {
    [[ $1 =~ ^[0-9]{1,5}$ ]] && (( 10#$1 >= 1 && 10#$1 <= 65535 ))
}

printf '\n=== Xray VPS Autodeploy: интерактивная установка ===\n'
printf '%s\n' 'Только чистый VPS. Оставьте значение пустым для выбора значения в [скобках].'
printf '%s\n' 'Сохраните вторую SSH-сессию и проверьте порты TCP 80/443 у провайдера.'
printf '\n'

while :; do
    prompt 'DuckDNS-домен (без https://)' 'vpn-example.duckdns.org'
    DOMAIN=$REPLY_VALUE
    [[ $DOMAIN =~ ^[a-z0-9-]+[.]duckdns[.]org$ && $DOMAIN != vpn-example.duckdns.org ]] && break
    echo 'Укажите свой действительный домен вида myvpn.duckdns.org.'
done

while :; do
    prompt 'Email для сертификата Let’s Encrypt' 'admin@example.com'
    LE_EMAIL=$REPLY_VALUE
    [[ $LE_EMAIL =~ ^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+[.][A-Za-z]{2,}$ && $LE_EMAIL != admin@example.com ]] && break
    echo 'Введите настоящий email без пробелов.'
done

echo 'DuckDNS-токен необязателен: без токена домен должен уже указывать на IP нового VPS.'
read -r -s -p 'DuckDNS-токен (Enter = не использовать): ' DUCKDNS_TOKEN
printf '\n'
[[ -z $DUCKDNS_TOKEN || $DUCKDNS_TOKEN =~ ^[A-Za-z0-9_-]+$ ]] || die 'Недопустимый формат DuckDNS-токена.'

while :; do
    prompt 'Текущий SSH-порт сервера (не изменяет sshd)' '22'
    SSH_PORT=$REPLY_VALUE
    valid_port "$SSH_PORT" && break
    echo 'Введите корректный порт 1..65535.'
done

while :; do
    prompt 'VPN-порт' '443'
    VPN_PORT=$REPLY_VALUE
    valid_port "$VPN_PORT" && [[ $VPN_PORT != 80 && $VPN_PORT != 2096 && $VPN_PORT != "$SSH_PORT" ]] && break
    echo 'VPN-порт должен быть 1..65535, не 80/2096 и не SSH-порт.'
done

while :; do
    prompt 'WebSocket-путь' '/vpn-ws-2026'
    WS_PATH=$REPLY_VALUE
    [[ $WS_PATH =~ ^/[A-Za-z0-9/_-]{1,120}$ ]] && break
    echo 'Путь должен начинаться с / и содержать только буквы ASCII, цифры, /, _ или -.'
done

while :; do
    prompt 'Имя первого VPN-клиента' 'phone01'
    CLIENT_NAME=$REPLY_VALUE
    [[ $CLIENT_NAME =~ ^[A-Za-z0-9_-]{1,32}$ ]] && break
    echo 'Имя: 1..32 символа (латиница, цифры, _ и -).'
done

while :; do
    prompt 'Версия Xray-core' 'latest'
    XRAY_VERSION=$REPLY_VALUE
    [[ $XRAY_VERSION == latest || $XRAY_VERSION =~ ^v[0-9]+([.][0-9]+){2}$ ]] && break
    echo 'Допустимо latest или версия вида v26.10.31.'
done

printf '\n=== ПРОВЕРЬТЕ ПАРАМЕТРЫ ===\n'
printf 'DOMAIN=%s\nLE_EMAIL=%s\nSSH_PORT=%s\nVPN_PORT=%s\nWS_PATH=%s\nCLIENT_NAME=%s\nXUI_VERSION=v3.11.0\nXRAY_VERSION=%s\nSTRICT_FIREWALL=no\n' \
    "$DOMAIN" "$LE_EMAIL" "$SSH_PORT" "$VPN_PORT" "$WS_PATH" "$CLIENT_NAME" "$XRAY_VERSION"
if [[ -n $DUCKDNS_TOKEN ]]; then
    echo 'DuckDNS token: задан (скрыт); установщик обновит A-запись указанного домена.'
else
    echo 'DuckDNS token: не задан; A-запись должна быть настроена вручную.'
fi
printf '\n'
read -r -p 'Для сохранения настроек и начала установки введите INSTALL: ' approval
[[ $approval == INSTALL ]] || die 'Отменено до создания config.env. Ничего не установлено.'

# printf %q produces shell-safe sourceable values; all values were validated.
{
    printf '# Generated by scripts/setup_interactive.sh. PRIVATE: never commit.\n'
    for name in DOMAIN LE_EMAIL DUCKDNS_TOKEN SSH_PORT VPN_PORT WS_PATH CLIENT_NAME XRAY_VERSION; do
        printf '%s=%q\n' "$name" "${!name}"
    done
    printf 'XUI_VERSION=v3.11.0\nSTRICT_FIREWALL=no\n'
} > "$CFG"
chmod 600 "$CFG"
printf '\nНастройки сохранены: %s (600). Запуск install.sh...\n' "$CFG"
exec bash "$BASE/install.sh"
